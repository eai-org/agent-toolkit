def backend_controller(tag):
    eps = [e for e in ENDPOINTS if e[0] == tag]
    dtos = sorted({x.rstrip("[]") for e in eps for x in (e[5], e[6]) if x and x != "multipart"})
    f = F("import { BadRequestException, Body, Controller, Delete, Get, HttpCode, Param, ParseUUIDPipe, Post, Put, Query, UploadedFile, UseGuards, UseInterceptors } from '@nestjs/common';",
          "import { FileInterceptor } from '@nestjs/platform-express';",
          "import { AuthGuard } from '../auth/auth.guard';",
          "import { PermissionGuard, RequirePermission } from '../auth/permission.guard';",
          "import { AuditTrail } from '../audit/audit-trail';",
          "import { %sHandler } from './handlers/%s.handler';" % (tag, kebab(tag)),
          "import { ListFindingsQuery, ListInspectionsQuery, PageQuery } from './dto/queries';")
    for d in dtos:
        f.add("import { %s } from './dto/%s';" % (d, kebab(d)))
    f.add("", "/**", " * %s endpoints of the v2 API. Every route checks one permission; see auth/permissions.ts" % tag,
          " * for the roles that hold it.", " */", "@Controller()", "@UseGuards(AuthGuard, PermissionGuard)",
          "export class %sController {" % tag,
          "  constructor(private readonly handler: %sHandler, private readonly audit: AuditTrail) {}" % tag)
    for _, opid, method, path, query, body, resp, perm, summary in eps:
        nest_path = re.sub(r"{(\w+)}", r":\1", path)
        pnames = re.findall(r"{(\w+)}", path)
        args = ["    @Param('%s', ParseUUIDPipe) %s: string," % (p, p) for p in pnames]
        if query:
            qcls = {"listInspections": "ListInspectionsQuery", "listFindings": "ListFindingsQuery"}.get(opid, "PageQuery")
            args.append("    @Query() query: %s," % qcls)
        if body == "multipart":
            args.append("    @UploadedFile() file: Express.Multer.File | undefined,")
        elif body:
            args.append("    @Body() body: %s," % body)
        ret = ("%s" % resp.replace("[]", "[]")) if resp else "void"
        call_args = ", ".join(pnames + (["query"] if query else []) + (["file"] if body == "multipart" else ["body"] if body else []))
        f.add("", "  /**", "   * %s" % summary, "   * Permission: `%s`." % perm, "   */",
              "  @%s('%s')" % (method.capitalize(), nest_path), "  @RequirePermission('%s')" % perm)
        if not resp:
            f.add("  @HttpCode(204)")
        if body == "multipart":
            f.add("  @UseInterceptors(FileInterceptor('file', { limits: { fileSize: 15 * 1024 * 1024 } }))")
        f.add("  async %s(" % opid, *args, "  ): Promise<%s> {" % ret)
        if body == "multipart":
            f.add("    if (!file) {", "      throw new BadRequestException('multipart field \"file\" is required');", "    }")
        if resp:
            f.add("    const result = await this.handler.%s(%s);" % (opid, call_args),
                  "    this.audit.record('%s', { %s });" % (perm, ", ".join(pnames) or "count: 1"),
                  "    return result;")
        else:
            f.add("    await this.handler.%s(%s);" % (opid, call_args),
                  "    this.audit.record('%s', { %s });" % (perm, ", ".join(pnames)))
        f.add("  }")
    return f.add("}")


