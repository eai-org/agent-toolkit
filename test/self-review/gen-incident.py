class F:
    """A file built line by line; mark() records the 1-based number of the next line added."""

    def __init__(self, *lines):
        self.lines, self.marks = [], {}
        self.add(*lines)

    def add(self, *lines):
        for line in lines:
            self.lines.extend(line.split("\n"))
        return self

    def block(self, text, **kw):
        text = textwrap.dedent(text).strip("\n")
        for k, v in kw.items():
            text = text.replace("<<" + k + ">>", str(v))
        return self.add(text)

    def mark(self, name):
        self.marks[name] = len(self.lines) + 1
        return self


class Tree:
    def __init__(self, root):
        self.root = root

    def write(self, rel, content):
        lines = content.lines if isinstance(content, F) else content
        path = os.path.join(self.root, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write("\n".join(lines) + "\n")


