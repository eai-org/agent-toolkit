def rotate_util():
    return F().block("""
        import { Rotation } from '@inspections/inspections/data-access';

        /**
         * Returns a copy of an image file rotated clockwise by `rotation` degrees, drawn on a canvas.
         * EXIF orientation is applied by the browser before drawing, so the result is upright.
         */
        export async function rotateImageFile(file: File, rotation: Rotation): Promise<File> {
          if (rotation === 0) {
            return file;
          }
          const bitmap = await createImageBitmap(file);
          const swap = rotation === 90 || rotation === 270;
          const canvas = document.createElement('canvas');
          canvas.width = swap ? bitmap.height : bitmap.width;
          canvas.height = swap ? bitmap.width : bitmap.height;
          const context = canvas.getContext('2d');
          if (!context) {
            throw new Error('canvas 2d context unavailable');
          }
          context.translate(canvas.width / 2, canvas.height / 2);
          context.rotate((rotation * Math.PI) / 180);
          context.drawImage(bitmap, -bitmap.width / 2, -bitmap.height / 2);
          const blob = await new Promise<Blob>((resolve, reject) =>
            canvas.toBlob((b) => (b ? resolve(b) : reject(new Error('encoding failed'))), file.type || 'image/jpeg', 0.92),
          );
          return new File([blob], file.name, { type: blob.type, lastModified: Date.now() });
        }
        """)


