def backend_legacy_routes():
    f = F().block("""
        import { Router, Request, Response, NextFunction } from 'express';
        import multer from 'multer';
        import { legacyStore } from './legacy-store';
        import { requireSession } from './session';

        /**
         * Legacy inspections API (v1). Frozen: kept until every tenant runs with InspectionsV2 enabled.
         * Query parameters are read exactly as named here; unknown ones are ignored.
         */
        export const legacyInspections = Router();
        const upload = multer({ limits: { fileSize: 10 * 1024 * 1024 } });

        function paging(req: Request): { page: number; pageSize: number } {
          const page = Math.max(1, Number(req.query.page ?? 1));
          const pageSize = Math.min(200, Math.max(1, Number(req.query.pageSize ?? 25)));
          return { page, pageSize };
        }

        function wrap(handler: (req: Request, res: Response) => Promise<void>) {
          return (req: Request, res: Response, next: NextFunction) => handler(req, res).catch(next);
        }
        """)
    for method, path, name in LEGACY_ROUTES:
        f.add("")
        if name == "uploadPhoto":
            f.block("""
                /** Uploads one photo; the file travels in the multipart field "photo". */
                legacyInspections.post('/findings/:id/photos', requireSession, upload.single('photo'), wrap(async (req, res) => {
                  if (!req.file) {
                    res.status(400).json({ error: 'multipart field "photo" is required' });
                    return;
                  }
                  res.status(201).json(await legacyStore.uploadPhoto(req.params.id, req.file));
                }));
                """)
        elif name in ("listInspections", "listFindings"):
            f.block("""
                /** <<name>>: paged by ?page and ?pageSize (default 25, at most 200). */
                legacyInspections.<<method>>('<<path>>', requireSession, wrap(async (req, res) => {
                  const { page, pageSize } = paging(req);
                  res.json(await legacyStore.<<name>>({ ...req.params, ...req.query, page, pageSize }));
                }));
                """, name=name, method=method, path=path)
        elif name == "rotatePhoto":
            f.block("""
                /** Rotates a stored photo by ?degrees (90, 180 or 270), server side. */
                legacyInspections.post('/photos/:id/rotate', requireSession, wrap(async (req, res) => {
                  const degrees = Number(req.body?.degrees ?? req.query.degrees);
                  if (![90, 180, 270].includes(degrees)) {
                    res.status(400).json({ error: 'degrees must be 90, 180 or 270' });
                    return;
                  }
                  res.json(await legacyStore.rotatePhoto(req.params.id, degrees));
                }));
                """)
        else:
            status = "204" if method == "delete" else "201" if method == "post" else "200"
            f.block("""
                /** <<name>> */
                legacyInspections.<<method>>('<<path>>', requireSession, wrap(async (req, res) => {
                  const result = await legacyStore.<<name>>(req.params.id, req.body);
                  res.status(<<status>>).json(result ?? null);
                }));
                """, name=name, method=method, path=path, status=status)
    return f


