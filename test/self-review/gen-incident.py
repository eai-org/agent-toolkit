def backend_dto(name, fields):
    refs = sorted({f[1].rstrip("[]") for f in fields if f[1].rstrip("[]") in SCHEMAS and f[1].rstrip("[]") != name})
    enums = sorted({f[1] for f in fields if f[1] in ENUMS})
    f = F("import { Type } from 'class-transformer';",
          "import { IsArray, IsBoolean, IsIn, IsInt, IsISO8601, IsNumber, IsOptional, IsString, IsUUID, Max, MaxLength, Min, ValidateNested } from 'class-validator';")
    for r in refs:
        f.add("import { %s } from './%s';" % (r, kebab(r)))
    if enums:
        consts = [re.sub(r"(?<!^)(?=[A-Z])", "_", e).upper() + "_VALUES" for e in enums]
        f.add("import { %s } from '../enums';" % ", ".join(sorted(enums + consts)))
    f.add("", "/**", " * %s of the v2 inspections API." % name, " * Field names and nullability are mirrored in backend/openapi/inspections-v2.json.", " */",
          "export class %s {" % name)
    for fld in fields:
        field, t, nullable = fld[0], fld[1], len(fld) > 2
        f.add("", "  /** %s */" % DESCRIPTIONS.get(field, "%s of the %s." % (field, name.replace("Dto", "").lower())))
        if nullable:
            f.add("  @IsOptional()")
        base_t = t.rstrip("[]")
        if t.endswith("[]"):
            f.add("  @IsArray()")
        if base_t == U:
            f.add("  @IsUUID('4'%s)" % (", { each: true }" if t.endswith("[]") else ""))
            ts = "string"
        elif base_t == S:
            f.add("  @IsString()", "  @MaxLength(%d)" % (4000 if field in ("description", "notes", "body") else 200))
            ts = "string"
        elif base_t == I:
            f.add("  @IsInt()", "  @Min(0)")
            ts = "number"
        elif base_t == N:
            f.add("  @IsNumber()", "  @Min(0)", "  @Max(1)")
            ts = "number"
        elif base_t == B:
            f.add("  @IsBoolean()")
            ts = "boolean"
        elif base_t in (D, T):
            f.add("  @IsISO8601({ strict: true })")
            ts = "string"
        elif base_t in ENUMS:
            f.add("  @IsIn(%s_VALUES)" % re.sub(r"(?<!^)(?=[A-Z])", "_", base_t).upper())
            ts = base_t
        else:
            f.add("  @ValidateNested(%s)" % ("{ each: true }" if t.endswith("[]") else ""), "  @Type(() => %s)" % base_t)
            ts = base_t
        if t.endswith("[]"):
            ts += "[]"
        f.add("  %s%s: %s%s;" % (field, "?" if nullable else "!", ts, " | null" if nullable else ""))
    return f.add("}")


