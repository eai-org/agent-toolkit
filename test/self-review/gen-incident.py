def kebab(s):
    return re.sub(r"(?<!^)(?=[A-Z])", "-", s).lower()


def pascal(s):
    return s[0].upper() + s[1:]


def ts_type(schema, imports):
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        imports.add(name)
        t = name
    elif schema.get("type") == "array":
        t = "Array<" + ts_type(schema["items"], imports) + ">"
    elif schema.get("type") in ("integer", "number"):
        t = "number"
    elif schema.get("type") == "boolean":
        t = "boolean"
    elif schema.get("format") == "binary":
        t = "Blob"
    else:
        t = "string"
    if schema.get("nullable"):
        t += " | null"
    return t


def import_lines(imports, prefix, own=None):
    return ["import { %s } from '%smodels/%s';" % (n, prefix, kebab(n)) for n in sorted(imports) if n != own]


def model_file(name, schema):
    lines = list(HEADER)
    if "enum" in schema:
        values = " | ".join(repr(v) for v in schema["enum"])
        return lines + ["export type %s = %s;" % (name, values)]
    imports, body = set(), []
    required = set(schema.get("required", []))
    for field, prop in schema["properties"].items():
        if prop.get("description"):
            body += ["", "  /**", "   * " + prop["description"], "   */"]
        body.append("  '%s'%s: %s;" % (field, "" if field in required else "?", ts_type(prop, imports)))
    own = import_lines(imports, "../", own=name)
    return lines + own + ([""] if own else []) + ["export interface %s {" % name] + body + ["}"]


def response_type(op, imports):
    schema = op.get("responses", {}).get("200", {}).get("content", {}).get("application/json", {}).get("schema")
    return ts_type(schema, imports) if schema else "void"


