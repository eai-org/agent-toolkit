PRIMS = {S: {"type": "string"}, U: {"type": "string", "format": "uuid"}, I: {"type": "integer", "format": "int32"},
         N: {"type": "number", "format": "double"}, B: {"type": "boolean"}, D: {"type": "string", "format": "date"},
         T: {"type": "string", "format": "date-time"}}


def prop(t, nullable=False):
    if t.endswith("[]"):
        p = {"type": "array", "items": prop(t[:-2])}
    elif t in ENUMS or t in SCHEMAS:
        p = {"$ref": "#/components/schemas/" + t}
    else:
        p = dict(PRIMS[t])
    if nullable:
        p["nullable"] = True
    return p


def openapi():
    schemas = {}
    for name, values in ENUMS.items():
        schemas[name] = {"type": "integer" if isinstance(values[0], int) else "string", "enum": values}
    for name, fields in SCHEMAS.items():
        props, required = {}, []
        for f in fields:
            p = prop(f[1], len(f) > 2)
            if f[0] in DESCRIPTIONS:
                p["description"] = DESCRIPTIONS[f[0]]
            props[f[0]] = p
            if len(f) == 2:
                required.append(f[0])
        schemas[name] = {"type": "object", "properties": props, "required": required, "additionalProperties": False}
    paths = {}
    for tag, opid, method, path, query, body, resp, perm, summary in ENDPOINTS:
        params = [{"name": n, "in": "path", "required": True, "schema": prop(U)} for n in re.findall(r"{(\w+)}", path)]
        for n, t in query:
            p = {"name": n, "in": "query", "required": False, "schema": prop(t)}
            if n == "pageSize":
                p["schema"].update({"minimum": 1, "maximum": 100, "default": 25})
                p["description"] = DESCRIPTIONS["pageSize"]
            params.append(p)
        op = {"tags": [tag], "operationId": opid, "summary": summary, "x-permission": perm, "parameters": params}
        if body == "multipart":
            op["requestBody"] = {"required": True, "content": {"multipart/form-data": {"schema": {
                "type": "object", "required": ["file"], "properties": {"file": {"type": "string", "format": "binary"}}}}}}
        elif body:
            op["requestBody"] = {"required": True, "content": {"application/json": {"schema": prop(body)}}}
        responses = {}
        if resp:
            responses["200"] = {"description": "OK", "content": {"application/json": {"schema": prop(resp)}}}
        else:
            responses["204"] = {"description": "No Content"}
        responses["400"] = {"description": "Validation failed"}
        responses["403"] = {"description": "Missing permission " + perm}
        responses["404"] = {"description": "Not found"}
        op["responses"] = responses
        paths.setdefault(path, {})[method] = op
    return {"openapi": "3.0.3", "info": {"title": "Inspections API", "version": "2.0.0"}, "paths": paths,
            "components": {"schemas": schemas}}


